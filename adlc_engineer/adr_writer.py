"""Persist the generated ADR as a numbered file under <repo>/docs/adr/ (--write-adr).

Only ever creates new files: existing ADRs are never overwritten or edited, and the
README index only gains a row.
"""

import datetime
import os
import re

ADR_DIR = os.path.join("docs", "adr")
_ADR_FILE_RE = re.compile(r"^(\d{4})-.+\.md$")
_INDEX_ROW_RE = re.compile(r"^\| \[\d{4}\]")


def slugify(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug or "decision"


def next_adr_number(adr_dir: str) -> int:
    if not os.path.isdir(adr_dir):
        return 1
    numbers = [int(m.group(1)) for name in os.listdir(adr_dir) if (m := _ADR_FILE_RE.match(name))]
    return max(numbers, default=0) + 1


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render_adr(number: int, title: str, modernization: dict, today: str, challenger: dict = None) -> str:
    """Render in the same shape as the hand-written ADRs: context, decision drivers,
    options considered, decision, consequences, follow-up actions."""
    recommended = modernization.get("recommended_option", "")
    chosen = next((o for o in modernization.get("options", []) if o["name"] == recommended), None)

    lines = [
        f"# ADR {number:04d}: {title}\n",
        "**Status:** Proposed (generated by ADLC Engineer; review before accepting)\n",
        f"**Date:** {today}\n",
        "## Context\n",
        modernization.get("adr", "").strip(),
        "",
        "## Decision Drivers\n",
    ]
    if chosen:
        lines.append(f"- {chosen['reasoning']}")
        if chosen.get("citations"):
            lines.append(f"- Evidence: {', '.join(f'`{c}`' for c in chosen['citations'])}")
    else:
        lines.append("- _No reasoning available for the recommended option._")
    lines.append("")

    lines.append("## Options Considered\n")
    for index, option in enumerate(modernization.get("options", [])):
        lines.append(f"### {chr(65 + index)}. {option['name']} — {option['recommendation']}\n")
        lines.append(
            f"Cost: {option['cost']}; risk: {option['risk']}; complexity: {option['complexity']}; "
            f"scalability: {option['scalability']}.\n"
        )
        lines.append(f"{option['reasoning']}\n")

    lines.append("## Decision\n")
    lines.append(f"**Adopt {recommended}.**\n")
    if challenger and challenger.get("has_objections"):
        personas = ", ".join(challenger.get("objecting_personas", []))
        lines.append(
            f"> The Architecture Challenger raised objections ({personas}); this is the revised "
            "recommendation. Read the full report before accepting.\n"
        )

    lines.append("## Consequences\n")
    lines.append("**Negative / risks accepted:**")
    risks = modernization.get("risks", [])
    lines.extend(f"- {risk}" for risk in risks) if risks else lines.append("- _None recorded._")
    lines.append("")

    lines.append("## Follow-up Actions\n")
    roadmap = modernization.get("migration_roadmap", [])
    lines.extend(f"- [ ] {step}" for step in roadmap) if roadmap else lines.append("- [ ] _None recorded._")
    lines.append("")
    return "\n".join(lines)


def _add_index_row(adr_dir: str, number: int, filename: str, title: str) -> bool:
    readme = os.path.join(adr_dir, "README.md")
    if not os.path.isfile(readme):
        return False
    with open(readme, "r", encoding="utf-8") as f:
        lines = f.read().split("\n")
    last_row = max((i for i, line in enumerate(lines) if _INDEX_ROW_RE.match(line)), default=None)
    if last_row is None:
        return False
    lines.insert(last_row + 1, f"| [{number:04d}]({filename}) | {_cell(title)} | Proposed |")
    with open(readme, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    return True


def write_adr(repo_path: str, modernization: dict, today: str = None, challenger: dict = None):
    """Write a new Proposed ADR for the recommended option.

    Returns (path, indexed): the new file's path, and whether a row was added to the
    README index (False when there is no README or it has no index table yet).
    """
    today = today or datetime.date.today().isoformat()
    recommended = modernization.get("recommended_option", "modernization approach")
    title = f"Adopt {recommended}"
    adr_dir = os.path.join(repo_path, ADR_DIR)
    os.makedirs(adr_dir, exist_ok=True)

    number = next_adr_number(adr_dir)
    filename = f"{number:04d}-{slugify(title)}.md"
    path = os.path.join(adr_dir, filename)
    # "x" mode refuses to touch an existing file.
    with open(path, "x", encoding="utf-8") as f:
        f.write(render_adr(number, title, modernization, today, challenger))
    indexed = _add_index_row(adr_dir, number, filename, title)
    return path, indexed
