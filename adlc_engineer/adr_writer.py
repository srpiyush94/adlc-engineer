"""Persist the generated ADR as a numbered file under <repo>/docs/adr/ (--write-adr).

Only ever creates new files: existing ADRs are never overwritten or edited, and the
README index only gains a row.
"""

import datetime
import os
import re

ADR_DIR = os.path.join("docs", "adr")
_ADR_FILE_RE = re.compile(r"^(\d{4})-.+\.md$")
_INDEX_ROW_RE = re.compile(r"^\| \[\d{4}\]")


def slugify(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug or "decision"


def next_adr_number(adr_dir: str) -> int:
    if not os.path.isdir(adr_dir):
        return 1
    numbers = [int(m.group(1)) for name in os.listdir(adr_dir) if (m := _ADR_FILE_RE.match(name))]
    return max(numbers, default=0) + 1


def render_adr(number: int, title: str, modernization: dict, today: str) -> str:
    lines = [
        f"# {number:04d}. {title}\n",
        "Status: Proposed",
        f"Date: {today}",
        "Source: generated by ADLC Engineer; review before accepting.\n",
        "## Options considered\n",
    ]
    for option in modernization.get("options", []):
        lines.append(f"- **{option['name']}** ({option['recommendation']}) — {option['reasoning']}")
    lines.append("")
    lines.append("## Decision record\n")
    lines.append(modernization.get("adr", "").strip())
    lines.append("")
    if modernization.get("risks"):
        lines.append("## Risks\n")
        lines.extend(f"- {risk}" for risk in modernization["risks"])
        lines.append("")
    return "\n".join(lines)


def _add_index_row(adr_dir: str, number: int, filename: str, title: str) -> bool:
    readme = os.path.join(adr_dir, "README.md")
    if not os.path.isfile(readme):
        return False
    with open(readme, "r", encoding="utf-8") as f:
        lines = f.read().split("\n")
    last_row = max((i for i, line in enumerate(lines) if _INDEX_ROW_RE.match(line)), default=None)
    if last_row is None:
        return False
    lines.insert(last_row + 1, f"| [{number:04d}]({filename}) | {title} | Proposed |")
    with open(readme, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    return True


def write_adr(repo_path: str, modernization: dict, today: str = None) -> str:
    """Write a new Proposed ADR for the recommended option; return its path."""
    today = today or datetime.date.today().isoformat()
    recommended = modernization.get("recommended_option", "modernization approach")
    title = f"Adopt {recommended}"
    adr_dir = os.path.join(repo_path, ADR_DIR)
    os.makedirs(adr_dir, exist_ok=True)

    number = next_adr_number(adr_dir)
    filename = f"{number:04d}-{slugify(title)}.md"
    path = os.path.join(adr_dir, filename)
    # "x" mode refuses to touch an existing file.
    with open(path, "x", encoding="utf-8") as f:
        f.write(render_adr(number, title, modernization, today))
    _add_index_row(adr_dir, number, filename, title)
    return path
